/**
 * Unified Response Types for Hybrid AI Approach
 * 
 * This module defines the standardized response schemas that all AI services
 * must return, ensuring consistent data flow and proper project ID tracking.
 */

// ============================================================================
// CORE RESPONSE INTERFACES
// ============================================================================

/**
 * Base response interface that all AI responses must extend
 * Ensures project ID is always included for proper user tracking
 */
export interface BaseAIResponse {
  /** Project ID for tracking responses back to specific users */
  projectId: string;
  /** Timestamp when the response was generated */
  timestamp: string;
  /** Success status of the AI operation */
  success: boolean;
  /** Error message if operation failed */
  error?: string;
}

/**
 * Regional Analysis Response
 * Generated by the regional analysis service
 */
export interface RegionalAnalysisResponse extends BaseAIResponse {
  /** Type identifier for response routing */
  type: 'regional_analysis';
  /** Regional context data */
  data: {
    cityState: string;
    primaryClassification: 'Hurricane Zone' | 'Earthquake Zone' | 'Tornado Alley' | 'Standard Region';
    secondaryClassifications: string[];
    climateZone: string;
    seasonalFactors: {
      winterLimitations: boolean;
      summerChallenges: boolean;
      rainySeason: string | null;
      optimalConstructionMonths: string[];
    };
    regulatoryEnvironment: {
      permitComplexity: 'Low' | 'Medium' | 'High';
      inspectionFrequency: 'Standard' | 'Enhanced' | 'Minimal';
      codeStrictness: 'Standard' | 'Strict' | 'Lenient';
      specialRequirements: string[];
    };
    marketConditions: {
      laborAvailability: 'High' | 'Medium' | 'Low';
      materialCosts: 'Below Average' | 'Average' | 'Above Average';
      contractorAvailability: 'High' | 'Medium' | 'Low';
      permitTimeline: 'Fast' | 'Standard' | 'Slow';
    };
    multipliers: {
      weatherDependent: number;
      permitComplexity: number;
      laborAvailability: number;
      materialCosts: number;
    };
    recommendations: string[];
  };
}

