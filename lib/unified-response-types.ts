// ============================================================================
// RESPONSE PARSING UTILITIES
// ============================================================================

/**
 * Type guard to check if a response is a valid BaseAIResponse
 */
export function isBaseAIResponse(response: any): response is BaseAIResponse {
  return (
    typeof response === 'object' &&
    response !== null &&
    typeof response.projectId === 'string' &&
    typeof response.timestamp === 'string' &&
    typeof response.success === 'boolean'
  );
}

/**
 * Type guard to check if a response is a RegionalAnalysisResponse
 */
export function isRegionalAnalysisResponse(response: any): response is RegionalAnalysisResponse {
  return (
    isBaseAIResponse(response) &&
    response.type === 'regional_analysis' &&
    typeof response.data === 'object'
  );
}

/**
 * Type guard to check if a response is a ProjectContextResponse
 */
export function isProjectContextResponse(response: any): response is ProjectContextResponse {
  return (
    isBaseAIResponse(response) &&
    response.type === 'project_context' &&
    typeof response.data === 'object'
  );
}

/**
 * Type guard to check if a response is a PhaseSpecificResponse
 */
export function isPhaseSpecificResponse(response: any): response is PhaseSpecificResponse {
  return (
    isBaseAIResponse(response) &&
    response.type === 'phase_specific' &&
    typeof response.data === 'object' &&
    typeof response.data.phaseId === 'string'
  );
}

/**
 * Type guard to check if a response is a MainRoadmapResponse
 */
export function isMainRoadmapResponse(response: any): response is MainRoadmapResponse {
  return (
    isBaseAIResponse(response) &&
    response.type === 'main_roadmap' &&
    typeof response.data === 'object'
  );
}

// ============================================================================
// RESPONSE VALIDATION
// ============================================================================

/**
 * Validates that a response contains all required fields
 */
export function validateResponse(response: any): { valid: boolean; errors: string[] } {
  const errors: string[] = [];

  if (!isBaseAIResponse(response)) {
    errors.push('Response must extend BaseAIResponse');
    return { valid: false, errors };
  }

  if (!response.projectId || typeof response.projectId !== 'string') {
    errors.push('Project ID is required and must be a string');
  }

  if (!response.timestamp || typeof response.timestamp !== 'string') {
    errors.push('Timestamp is required and must be a string');
  }

  if (typeof response.success !== 'boolean') {
    errors.push('Success field is required and must be a boolean');
  }

  if (response.success === false && !response.error) {
    errors.push('Error message is required when success is false');
  }

  return {
    valid: errors.length === 0,
    errors
  };
}

// ============================================================================
// RESPONSE CREATION HELPERS
// ============================================================================

/**
 * Creates a base response with common fields
 */
export function createBaseResponse(projectId: string, success: boolean = true, error?: string): BaseAIResponse {
  return {
    projectId,
    timestamp: new Date().toISOString(),
    success,
    error
  };
}

/**
 * Creates a successful response with data
 */
export function createSuccessResponse<T extends BaseAIResponse>(
  projectId: string,
  type: T['type'],
  data: T['data']
): T {
  return {
    ...createBaseResponse(projectId, true),
    type,
    data
  } as T;
}

/**
 * Creates an error response
 */
export function createErrorResponse<T extends BaseAIResponse>(
  projectId: string,
  type: T['type'],
  error: string
): T {
  return {
    ...createBaseResponse(projectId, false, error),
    type,
    data: {} as T['data']
  } as T;
}
